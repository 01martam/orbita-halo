double funcio_exacta(double t, double *prm){
       double r = prm[0],k=prm[1];
       double expo = exp(k*t);
       return r*expo/(expo+r-1);
}

int camp(int n,double t, double *x, double *f, double *prm){
    if(n!=1){return -1;}
    double r=prm[0],k=prm[1];
    *f = k* *x * (1 - *x/r);
    return 0;
}

